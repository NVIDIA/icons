/**
 * Generate THIRD_PARTY_NOTICES from the runtime dependencies of published
 * packages, and sync it to the repo root and every published package (npm
 * ships each package's own copy -- see each package's `files`).
 *
 * Scope is deliberately narrow: this repo currently ships zero third-party
 * runtime dependencies. If a published package ever gains one, this script
 * exits non-zero rather than guessing at license text -- adding a runtime
 * dependency to a published package is a licensing event that needs
 * hand-authored notice text and legal review, not autogenerated output.
 *
 * Usage: node scripts/generate-third-party-notices.mjs
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

const PUBLIC_PACKAGES = [
  "packages/gui-icons",
  "packages/micro-gui-icons",
  "packages/react-gui-icons",
  "packages/react-micro-gui-icons",
];

const manifests = PUBLIC_PACKAGES.map((pkgPath) => ({
  pkgPath,
  pkg: JSON.parse(
    fs.readFileSync(path.join(REPO_ROOT, pkgPath, "package.json"), "utf-8"),
  ),
}));

// Workspace packages depend on each other (e.g. react-gui-icons depends on
// @nvidia/gui-icons). Those are first-party siblings published from this
// same repo, not third-party OSS -- exclude them before checking for
// anything that would actually need a notice.
const WORKSPACE_NAMES = new Set(manifests.map(({ pkg }) => pkg.name));

const runtimeDeps = new Set();
for (const { pkg } of manifests) {
  for (const dep of Object.keys(pkg.dependencies ?? {})) {
    if (!WORKSPACE_NAMES.has(dep)) runtimeDeps.add(dep);
  }
}

if (runtimeDeps.size > 0) {
  console.error("generate-third-party-notices: FAIL");
  console.error(
    `  Runtime dependencies detected: ${[...runtimeDeps].sort().join(", ")}`,
  );
  console.error(
    "  This repo ships with zero third-party runtime dependencies.",
  );
  console.error(
    "  Adding one requires legal review and hand-authored notice text --",
  );
  console.error(
    "  it must not be auto-generated. See CONTRIBUTING.md, and raise this",
  );
  console.error("  with the maintainers listed in MAINTAINERS.md.");
  process.exit(1);
}

// No runtime dependencies: the notice is static prose, not tool output, so
// it does not carry a generation timestamp -- a timestamp would make this
// file change on every run, which would defeat the CI drift check that runs
// this script and expects `git diff --exit-code` to pass afterward.
const CONTENT = `NVIDIA Icons — Third-Party Notices
==================================

This file lists the open-source components distributed in the published npm
packages. It is regenerated by scripts/generate-third-party-notices.mjs
before each release.

The four published packages (@nvidia/gui-icons, @nvidia/micro-gui-icons,
@nvidia/react-gui-icons, @nvidia/react-micro-gui-icons) have no bundled
runtime dependencies other than the peer dependency on React (react,
react-dom), which is provided by the consumer application and is NOT
distributed in the package tarballs.

Build-time devDependencies (vite, @vitejs/plugin-react, tsc, biome, etc.)
are used at build time only and are NOT distributed in published tarballs.

---------------------------------------------------------------------------
No third-party OSS components are currently bundled or distributed in these
packages. Update this file if runtime dependencies are added.
---------------------------------------------------------------------------

Generated by: scripts/generate-third-party-notices.mjs
`;

// Every published package ships its own copy (see each package's `files`),
// plus the repo root keeps one for the public-facing top-level view. All
// five must be byte-identical -- see scripts/verify-packaging.mjs, which
// enforces that as a CI gate.
const TARGETS = [
  path.join(REPO_ROOT, "THIRD_PARTY_NOTICES"),
  ...PUBLIC_PACKAGES.map((pkgPath) =>
    path.join(REPO_ROOT, pkgPath, "THIRD_PARTY_NOTICES"),
  ),
];

for (const target of TARGETS) {
  fs.writeFileSync(target, CONTENT, "utf-8");
  console.log(`✓ Written ${path.relative(REPO_ROOT, target)}`);
}
